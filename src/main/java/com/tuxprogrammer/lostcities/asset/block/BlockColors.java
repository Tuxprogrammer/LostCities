package com.tuxprogrammer.lostcities.asset.block;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.Reader;
import java.nio.charset.StandardCharsets;
import java.util.Collections;
import java.util.HashMap;
import java.util.Map;

import com.tuxprogrammer.lostcities.asset.BlockRef;
import com.tuxprogrammer.lostcities.asset.Problems;

/**
 * The measured color of every block the decorative catalog's contact sheets name: the mean of its side face's opaque
 * pixels, averaged in linear light, and the share of its pixels that are opaque. Generated by
 * {@code tools/block-colors/measure.py} from the GTNH 2.9.0 jars and shipped as {@value #RESOURCE}, so world generation
 * never reads a texture (docs/design/0008-facade-color-feathering.md §1).
 *
 * <p>
 * Colors are also given in CIELAB (D65), which the contrast rule and the repair patches measure in. A block missing
 * from the table falls back to the same block's meta 0; otherwise it is unknown.
 *
 * <p>
 * Immutable. Side: both (plain Java).
 */
public final class BlockColors {

    /** The bundled table, inside the jar. */
    public static final String RESOURCE = "/data/lostcitiesnh/blockmap/colors.tsv";

    /** Coverage, in percent, under which a block counts as see-through (glass, panes, bars, plants). */
    public static final int OPAQUE_COVERAGE = 60;

    /** An empty table: every block is unknown. */
    public static final BlockColors EMPTY = new BlockColors(Collections.<String, Entry>emptyMap());

    /** One block's measured color. */
    public static final class Entry {

        private final int rgb;
        private final int coverage;
        private final float lightness;
        private final float a;
        private final float b;

        Entry(int rgb, int coverage) {
            this.rgb = rgb;
            this.coverage = coverage;
            float[] lab = lab(rgb);
            this.lightness = lab[0];
            this.a = lab[1];
            this.b = lab[2];
        }

        /** Returns the mean color as {@code 0xRRGGBB}. */
        public int rgb() {
            return rgb;
        }

        /** Returns the share of opaque pixels, 0 to 100. */
        public int coverage() {
            return coverage;
        }

        /** Returns whether the block reads as a solid wall (coverage of at least {@value #OPAQUE_COVERAGE} %). */
        public boolean isOpaque() {
            return coverage >= OPAQUE_COVERAGE;
        }

        /** Returns CIELAB lightness L*, 0 to 100. */
        public float lightness() {
            return lightness;
        }

        /** Returns CIELAB a*. */
        public float a() {
            return a;
        }

        /** Returns CIELAB b*. */
        public float b() {
            return b;
        }
    }

    private final Map<String, Entry> entries;

    private BlockColors(Map<String, Entry> entries) {
        this.entries = entries;
    }

    /**
     * Reads the bundled table from the class path.
     *
     * @param anchor   a class whose loader holds the resource
     * @param problems where a missing or malformed file is reported
     * @return the table; {@link #EMPTY} when it is missing
     */
    public static BlockColors bundled(Class<?> anchor, Problems problems) {
        try (InputStream in = anchor.getResourceAsStream(RESOURCE)) {
            if (in == null) {
                problems.in(BlockData.origin(RESOURCE))
                    .error("", null, "missing from the jar");
                return EMPTY;
            }
            return parse(new InputStreamReader(in, StandardCharsets.UTF_8), problems);
        } catch (IOException e) {
            problems.in(BlockData.origin(RESOURCE))
                .error("", null, "unreadable: " + e.getMessage());
            return EMPTY;
        }
    }

    /**
     * Parses the table's text: comment lines start with {@code #}; each other line is
     * {@code modid:name:meta<TAB>#rrggbb<TAB>coverage}.
     *
     * @param text     the table
     * @param problems where malformed lines are reported, one note each
     * @return the table
     * @throws IOException when the reader fails
     */
    public static BlockColors parse(Reader text, Problems problems) throws IOException {
        Map<String, Entry> out = new HashMap<>();
        BufferedReader reader = new BufferedReader(text);
        String line;
        int number = 0;
        while ((line = reader.readLine()) != null) {
            number++;
            if (line.isEmpty() || line.charAt(0) == '#') {
                continue;
            }
            String[] fields = line.split("\t");
            if (fields.length != 3 || fields[1].length() != 7 || fields[1].charAt(0) != '#') {
                problems.in(BlockData.origin(RESOURCE))
                    .error("line " + number, line, "expected block, #rrggbb and coverage");
                continue;
            }
            try {
                int rgb = Integer.parseInt(fields[1].substring(1), 16);
                int coverage = Integer.parseInt(fields[2]);
                out.put(fields[0], new Entry(rgb, Math.max(0, Math.min(100, coverage))));
            } catch (NumberFormatException e) {
                problems.in(BlockData.origin(RESOURCE))
                    .error("line " + number, line, "not a number: " + e.getMessage());
            }
        }
        return new BlockColors(Collections.unmodifiableMap(out));
    }

    /**
     * Returns a block's color: its own entry, or its meta 0 entry.
     *
     * @param block the block
     * @return the entry, or {@code null} when the block is unknown
     */
    public Entry get(BlockRef block) {
        if (block == null) {
            return null;
        }
        Entry entry = entries.get(block.name() + ":" + block.meta());
        if (entry == null && block.meta() != 0) {
            entry = entries.get(block.name() + ":0");
        }
        return entry;
    }

    /** Returns how many blocks the table holds. */
    public int size() {
        return entries.size();
    }

    /**
     * Converts an sRGB color to CIELAB under D65.
     *
     * @param rgb {@code 0xRRGGBB}
     * @return {L*, a*, b*}
     */
    public static float[] lab(int rgb) {
        double r = linear((rgb >> 16) & 0xFF);
        double g = linear((rgb >> 8) & 0xFF);
        double b = linear(rgb & 0xFF);
        double x = (0.4124 * r + 0.3576 * g + 0.1805 * b) / 0.95047;
        double y = 0.2126 * r + 0.7152 * g + 0.0722 * b;
        double z = (0.0193 * r + 0.1192 * g + 0.9505 * b) / 1.08883;
        double fx = f(x);
        double fy = f(y);
        double fz = f(z);
        return new float[] { (float) (116 * fy - 16), (float) (500 * (fx - fy)), (float) (200 * (fy - fz)) };
    }

    private static double linear(int channel) {
        double c = channel / 255.0;
        return c <= 0.04045 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4);
    }

    private static double f(double t) {
        return t > 0.008856 ? Math.cbrt(t) : 7.787 * t + 16.0 / 116.0;
    }
}
