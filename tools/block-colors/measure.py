#!/usr/bin/env python3
"""Measures the facade color of every block the contact sheets name, for color feathering (design record 0012).

Each block's side face (or its one face) is read from the mod jars in the reference pack, as the contact sheets read
it, tinted where the sheet says the game tints it. Its color is the mean of its opaque pixels, averaged in linear
light and written back as sRGB; its coverage is the share of pixels with alpha of at least 128. The table ships in the
jar as data, so world generation never reads a texture and a resource pack cannot change a city.

Usage:
    python3 -I tools/block-colors/measure.py [--sheets tools/block-contact-sheet/sheets] [--mods <dir>] \
        [--out src/main/resources/data/lostcitiesnh/blockmap/colors.tsv]
    python3 -I tools/block-colors/test_measure.py

Jars and textures are untrusted data: they are only opened as zip archives and decoded as images.
"""

import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(REPO / "tools" / "block-contact-sheet"))

import contact_sheet  # noqa: E402  (our own tool, next door)

LABEL = re.compile(r"^([A-Za-z0-9_.|\-]+:[A-Za-z0-9_.\-]+)(?::(\d+)(?:-(\d+))?)?$")
OPAQUE_ALPHA = 128
HEADER = (
    "# Block facade colors for color feathering (docs/design/0012-facade-color-feathering.md).\n"
    "# Generated by tools/block-colors/measure.py from the contact sheets' textures in the GTNH 2.9.0 jars.\n"
    "# Columns: block (modid:name:meta), mean opaque color (sRGB, averaged in linear light), opaque coverage 0-100.\n"
)


def expand(label):
    """The block refs a sheet label names: `mod:name:meta`, `mod:name:a-b` (each meta), `mod:name` (meta 0)."""
    match = LABEL.match(label.strip())
    if not match:
        return []
    name, first, last = match.group(1), match.group(2), match.group(3)
    if first is None:
        return [name + ":0"]
    low = int(first)
    high = int(last) if last is not None else low
    if high < low or high - low > 15:
        return []
    return ["%s:%d" % (name, meta) for meta in range(low, high + 1)]


def to_linear(channel):
    c = channel / 255.0
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def to_srgb(linear):
    c = linear * 12.92 if linear <= 0.0031308 else 1.055 * linear ** (1 / 2.4) - 0.055
    return max(0, min(255, int(round(c * 255))))


def measure(image):
    """(r, g, b, coverage%) of an RGBA image: the mean of its opaque pixels in linear light; None if none is."""
    raw = image.convert("RGBA").tobytes()
    pixels = [raw[i:i + 4] for i in range(0, len(raw), 4)]
    opaque = [p for p in pixels if p[3] >= OPAQUE_ALPHA]
    if not opaque:
        return None
    sums = [0.0, 0.0, 0.0]
    for p in opaque:
        for i in range(3):
            sums[i] += to_linear(p[i])
    n = len(opaque)
    rgb = tuple(to_srgb(s / n) for s in sums)
    return rgb + (int(round(100.0 * n / len(pixels))),)


def collect(sheets_dir, source):
    """{block ref: (r, g, b, coverage)} over every sheet; the first sheet (sorted by path) naming a block wins."""
    table = {}
    missing = []
    for path in sorted(Path(sheets_dir).rglob("*.json")):
        sheet = json.loads(path.read_text(encoding="utf-8"))
        for entry in sheet.get("entries", []):
            refs = [r for r in expand(entry.get("label", "")) if r not in table]
            if not refs:
                continue
            texture = entry.get("side") or entry.get("all")
            image = source.load(texture)
            if image is None:
                missing.append(entry.get("label"))
                continue
            image = contact_sheet.tint(image, entry.get("tint"))
            color = measure(image)
            if color is None:
                continue
            for ref in refs:
                table[ref] = color
    return table, missing


def write(table, out):
    lines = [HEADER]
    for ref in sorted(table):
        r, g, b, coverage = table[ref]
        lines.append("%s\t#%02x%02x%02x\t%d\n" % (ref, r, g, b, coverage))
    Path(out).write_text("".join(lines), encoding="utf-8")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--sheets", default=str(REPO / "tools" / "block-contact-sheet" / "sheets"))
    parser.add_argument("--mods", default=str(contact_sheet.default_mods_dir()))
    parser.add_argument("--out", default=str(REPO / "src/main/resources/data/lostcitiesnh/blockmap/colors.tsv"))
    args = parser.parse_args(argv)
    source = contact_sheet.TextureSource(args.mods)
    try:
        table, missing = collect(args.sheets, source)
    finally:
        source.close()
    write(table, args.out)
    print("%d blocks measured, %d textures missing" % (len(table), len(missing)))
    for label in missing[:40]:
        print("  missing: %s" % label)
    return 0


if __name__ == "__main__":
    sys.exit(main())
