#!/usr/bin/env python3
"""Stage upstream Lost Cities' pure classes for the parity recorder.

Run from anywhere inside this repository with ``python3 -I tools/upstream-parity/stage.py <out dir>``. It reads the
pinned upstream branch (``1.20`` at f18a094d) through ``git show``, writes the classes Recorder.java compiles against
into ``<out dir>/src``, and copies Recorder.java beside them. Upstream's files are compiled as they are, except for
two mechanical cuts that remove Minecraft dependencies the recorded methods never touch:

- StreetPlannerSettings loses ``fromProfile`` (it reads ``LostCityProfile``);
- the hash methods of HierarchicalBridgePlanner are lifted, unchanged, into ``BridgeHashes`` with two stub types
  (``IDimensionInfo``, ``ChunkCoord``) and ``Orientation``, because the planner itself reads ``BuildingInfo``.

Nothing staged here is committed; it lives in the output directory only.
"""
import pathlib
import re
import shutil
import subprocess
import sys

BASE = "src/main/java/mcjty/lostcities/"
PINNED = "1.20"
EXPECTED_COMMIT = "f18a094d"

PLAIN = [
    "varia/QualityRandom.java",
    "worldgen/street/HierarchicalStreetPlanner.java",
    "worldgen/street/PlannedRoadType.java",
    "worldgen/street/PlannedStreetInfo.java",
    "worldgen/street/RoadDirection.java",
    "worldgen/street/TertiaryRoadSegment.java",
    "worldgen/street/EffectiveStreetResolver.java",
]


def show(path):
    return subprocess.run(["git", "show", PINNED + ":" + BASE + path], check=True, capture_output=True,
                          text=True).stdout


def method(source, signature_start):
    """Return the full text of the method whose declaration starts with signature_start."""
    start = source.index(signature_start)
    depth = 0
    i = source.index("{", start)
    while True:
        if source[i] == "{":
            depth += 1
        elif source[i] == "}":
            depth -= 1
            if depth == 0:
                return source[start:i + 1]
        i += 1


def main():
    out = pathlib.Path(sys.argv[1]).resolve()
    commit = subprocess.run(["git", "rev-parse", PINNED], check=True, capture_output=True, text=True).stdout.strip()
    if not commit.startswith(EXPECTED_COMMIT):
        sys.exit("branch %s is at %s, not the pinned %s" % (PINNED, commit, EXPECTED_COMMIT))
    src = out / "src"
    if src.exists():
        shutil.rmtree(src)
    pkg = src / "mcjty/lostcities"
    for path in PLAIN:
        target = pkg / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(show(path))

    settings = show("worldgen/street/StreetPlannerSettings.java")
    settings = settings.replace("import mcjty.lostcities.config.LostCityProfile;\n", "")
    settings = settings.replace(method(settings, "public static StreetPlannerSettings fromProfile"), "")
    (pkg / "worldgen/street/StreetPlannerSettings.java").write_text(settings)

    bridge = show("worldgen/street/HierarchicalBridgePlanner.java")
    salts = re.findall(r"private static final long \w+ = 0x[0-9a-f]+L;", bridge)
    lifted = [method(bridge, "private static Orientation preferredIntersectionOrientation"),
              method(bridge, "private static long spanHash"),
              method(bridge, "private static double unitDouble"),
              method(bridge, "private static long stableStringHash"),
              method(bridge, "private static long mix64")]
    (pkg / "worldgen/street/BridgeHashes.java").write_text(
        "package mcjty.lostcities.worldgen.street;\n\n"
        "import mcjty.lostcities.varia.ChunkCoord;\n"
        "import mcjty.lostcities.worldgen.IDimensionInfo;\n"
        "import mcjty.lostcities.worldgen.lost.Orientation;\n\n"
        "/** Generated by stage.py: HierarchicalBridgePlanner's hash methods, lifted unchanged. */\n"
        "public final class BridgeHashes {\n"
        + "\n".join("    " + s for s in salts) + "\n\n"
        + "\n\n".join("    " + m for m in lifted) + "\n\n"
        "    public static String preferred(long seed, String dim) {\n"
        "        return preferredIntersectionOrientation(IDimensionInfo.of(seed, dim)).name();\n"
        "    }\n\n"
        "    public static long span(long seed, String dim, String orientation, int minX, int minZ, int maxX,"
        " int maxZ) {\n"
        "        return spanHash(IDimensionInfo.of(seed, dim), Orientation.valueOf(orientation),"
        " new ChunkCoord(minX, minZ), new ChunkCoord(maxX, maxZ), BRIDGE_SPAN_SALT);\n"
        "    }\n"
        "}\n")
    (pkg / "varia/ChunkCoord.java").write_text(
        "package mcjty.lostcities.varia;\n\n"
        "/** Stub with the two accessors the lifted hash methods call. */\n"
        "public record ChunkCoord(int chunkX, int chunkZ) { }\n")
    (pkg / "worldgen/lost").mkdir(parents=True, exist_ok=True)
    (pkg / "worldgen/lost/Orientation.java").write_text(
        "package mcjty.lostcities.worldgen.lost;\n\n/** Stub: upstream's two orientations. */\n"
        "public enum Orientation { X, Z }\n")
    (pkg / "worldgen/IDimensionInfo.java").write_text(
        "package mcjty.lostcities.worldgen;\n\n"
        "/** Stub with the two calls the lifted hash methods make: the seed and the dimension key's location. */\n"
        "public interface IDimensionInfo {\n"
        "    long getSeed();\n\n"
        "    Key getType();\n\n"
        "    interface Key { Object location(); }\n\n"
        "    static IDimensionInfo of(long seed, String dimension) {\n"
        "        return new IDimensionInfo() {\n"
        "            public long getSeed() { return seed; }\n\n"
        "            public Key getType() { return () -> dimension; }\n"
        "        };\n"
        "    }\n"
        "}\n")
    shutil.copy(pathlib.Path(__file__).with_name("Recorder.java"), src / "Recorder.java")
    print("staged upstream %s into %s" % (commit, src))


if __name__ == "__main__":
    main()
